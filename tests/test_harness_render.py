from __future__ import annotations

import json
import re
from dataclasses import replace

import pytest

from agent_introspection import facts
from scripts.lib.harness_render import render_harnesses

_REGISTRY = facts.Registry(signals=[], routes=[], support=[], strays=[], excluded=[])


def _module(harnesses: dict[str, str]) -> str:
    module: str = render_harnesses(replace(_REGISTRY, harnesses=harnesses))
    return module


def _constant(module: str, name: str) -> str:
    """Return the source of one exported constant, from its name to its semicolon."""
    return module.split(f"export const {name}", 1)[1].split(";\n", 1)[0]


@pytest.mark.parametrize(
    "harnesses",
    [
        pytest.param({"a": "A", "b-c": "B"}, id="short"),
        pytest.param(
            {"oh-my-pi": "omp", "codex_cli_rs": "Codex CLI", "opencode": "opencode"},
            id="registry-like",
        ),
        pytest.param({f"harness_{n}": f"Harness {n}" for n in range(9)}, id="long"),
    ],
)
def test_module_lists_every_harness_label_and_service_in_registry_order(
    harnesses: dict[str, str],
) -> None:
    module = _module(harnesses)

    assert "Generated by scripts/render-measures.py" in module.splitlines()[0]
    assert "Do not edit." in module.splitlines()[1]
    listed = re.findall(r'"([^"]+)"', _constant(module, "HARNESSES"))
    assert listed == list(harnesses)
    labels = _constant(module, "HARNESS_LABEL")
    for key, label in harnesses.items():
        name = key if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", key) else json.dumps(key)
        assert f"{name}: {json.dumps(label)}," in labels.replace(":\n    ", ": ")
    services = json.loads(_constant(module, "HARNESS_SERVICES_SQL").split("=", 1)[1].strip())
    assert services == ", ".join(map(facts.sql_string, harnesses))


def test_module_takes_the_layout_prettier_gives_it() -> None:
    short = _module({"a": "A", "b-c": "B"})
    long_label = "A harness label far too long to share a line with its key in Prettier"
    wide = _module({f"harness_{n}": long_label for n in range(9)})

    assert 'export const HARNESSES = ["a", "b-c"] as const;\n' in short
    assert "export const HARNESS_SERVICES_SQL = \"'a', 'b-c'\";\n" in short
    assert '  "b-c": "B",\n' in short
    assert 'export const HARNESSES = [\n  "harness_0",\n' in wide
    assert f'  harness_0:\n    "{long_label}",\n' in wide
    assert "export const HARNESS_SERVICES_SQL =\n  \"'harness_0', " in wide
    # Prettier never splits a string or reflows a comment; every other line fits in 80.
    code = [line for line in wide.splitlines() if '"' not in line and not line.startswith("/")]
    assert all(len(line) <= 80 for line in code)
