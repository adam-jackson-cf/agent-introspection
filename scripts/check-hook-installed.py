#!/usr/bin/env python3
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections.abc import Sequence
from pathlib import Path

import yaml

from lib import filesystem

_RULE = "GATE.enforced"
_MARKER = "# File generated by pre-commit: https://pre-commit.com"
_INSTALL_PYTHON = re.compile(r"^INSTALL_PYTHON=(?P<path>.+)$", re.MULTILINE)
_FIX = "run uv run pre-commit install"


def _git_path(name: str) -> str:
    completed = subprocess.run(
        ["git", "rev-parse", "--git-path", name],
        check=True,
        stdout=subprocess.PIPE,
        text=True,
        timeout=30,
    )
    return completed.stdout.strip()


def hook_types(config: Path) -> list[str]:
    data = yaml.safe_load(filesystem.read_text(config)) or {}
    types = data.get("default_install_hook_types", ["pre-commit"]) if isinstance(data, dict) else []
    if not isinstance(types, list) or not types or not all(isinstance(item, str) for item in types):
        raise ValueError(f"{config}: {_RULE}: default_install_hook_types must list hook types")
    return types


def hook_problems(hook: Path, config: str, hook_type: str) -> list[str]:
    if not filesystem.is_file(hook):
        return [f"{hook}: {_RULE}: {hook_type} hook is not installed; {_FIX}"]
    text = filesystem.read_text(hook)
    problems = []
    if not filesystem.is_executable(hook):
        problems.append(f"{hook}: {_RULE}: hook is not executable; {_FIX}")
    expected = f"--config={config} --hook-type={hook_type}"
    if _MARKER not in text or expected not in text:
        problems.append(f"{hook}: {_RULE}: hook does not run pre-commit with {config}; {_FIX}")
    interpreter = _INSTALL_PYTHON.search(text)
    if interpreter is not None and not filesystem.is_executable(interpreter.group("path").strip()):
        problems.append(f"{hook}: {_RULE}: hook interpreter is missing; {_FIX}")
    return problems


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Fail when the pre-commit hook is not installed.")
    parser.add_argument("config", type=Path)
    args = parser.parse_args(argv)
    try:
        types = hook_types(args.config)
    except (OSError, ValueError, yaml.YAMLError) as error:
        print(error, file=sys.stderr)
        return 1
    problems: list[str] = []
    for hook_type in types:
        hook = Path(_git_path(f"hooks/{hook_type}"))
        found = hook_problems(hook, args.config.as_posix(), hook_type)
        problems += found
        if not found:
            print(f"pre-commit hook installed: {hook}")
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
